-- Rowglow demo database (PostgreSQL)
DROP SCHEMA IF EXISTS shop CASCADE;
CREATE SCHEMA shop;
SET search_path TO shop, public;

CREATE TYPE order_status AS ENUM ('pending', 'paid', 'shipped', 'refunded');

CREATE TABLE customers (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email       text NOT NULL UNIQUE,
  full_name   text NOT NULL,
  country     char(2) NOT NULL DEFAULT 'US',
  marketing   boolean NOT NULL DEFAULT false,
  metadata    jsonb,
  created_at  timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE customers IS 'People who bought something';
COMMENT ON COLUMN customers.metadata IS 'Free-form JSON from signup';

CREATE TABLE products (
  id          serial PRIMARY KEY,
  sku         text NOT NULL UNIQUE,
  name        text NOT NULL,
  price       numeric(10,2) NOT NULL CHECK (price >= 0),
  tags        text[] NOT NULL DEFAULT '{}',
  in_stock    integer NOT NULL DEFAULT 0
);

CREATE TABLE orders (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id  bigint NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
  status       order_status NOT NULL DEFAULT 'pending',
  total        numeric(12,2) NOT NULL DEFAULT 0,
  note         text,
  placed_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX orders_customer_idx ON orders(customer_id);
CREATE INDEX orders_status_placed_idx ON orders(status, placed_at DESC);

CREATE TABLE order_items (
  order_id    bigint NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  product_id  integer NOT NULL REFERENCES products(id),
  quantity    integer NOT NULL CHECK (quantity > 0),
  unit_price  numeric(10,2) NOT NULL,
  PRIMARY KEY (order_id, product_id)
);

CREATE TABLE audit_log (
  at      timestamptz NOT NULL DEFAULT now(),
  action  text NOT NULL,
  detail  text
);

