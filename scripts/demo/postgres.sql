CREATE VIEW customer_revenue AS
SELECT c.id, c.full_name, c.country, count(o.id) AS orders, coalesce(sum(o.total), 0) AS revenue
FROM customers c LEFT JOIN orders o ON o.customer_id = c.id AND o.status IN ('paid', 'shipped')
GROUP BY c.id;

CREATE MATERIALIZED VIEW daily_sales AS
SELECT date_trunc('day', placed_at)::date AS day, count(*) AS orders, sum(total) AS revenue
FROM orders WHERE status IN ('paid','shipped') GROUP BY 1 ORDER BY 1;

CREATE FUNCTION order_count(cust bigint) RETURNS bigint LANGUAGE sql STABLE AS $$
  SELECT count(*) FROM shop.orders WHERE customer_id = cust;
$$;

CREATE FUNCTION touch_audit() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  INSERT INTO shop.audit_log(action, detail) VALUES (TG_OP, 'orders ' || coalesce(NEW.id, OLD.id));
  RETURN NULL;
END $$;
CREATE TRIGGER orders_audit AFTER UPDATE OF status ON orders FOR EACH ROW EXECUTE FUNCTION touch_audit();

